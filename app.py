# Әр пән үшін вкладкалар (табтар) жасау
tabs = st.tabs(list(SUBJECTS_DATA.keys()))

for index, (subject, items) in enumerate(SUBJECTS_DATA.items()):
    with tabs[index]:
        st.header(subject)
        
        for item_idx, item in enumerate(items):
            st.subheader(item["title"])
            st.write(item["description"])
            st.markdown(f"**[👉 {item['title']} онлайн көру]({item['link']})**")
            
            # Ашылатын блок ішіндегі квиз
            with st.expander(f"🧠 Мына тақырып бойынша квиз тапсыру: {item['title']}"):
                form_key = f"quiz_form_{subject}_{item_idx}"
                with st.form(key=form_key):
                    user_answers = []
                    
                    for q_idx, q in enumerate(item["quiz"]):
                        st.write(q["question"])
                        radio_key = f"q_{subject}_{item_idx}_{q_idx}"
                        choice = st.radio(
                            "Жауапты таңдаңыз:", 
                            q["options"], 
                            key=radio_key,
                            index=None # Бастапқыда ешқайсысы таңдалмауы үшін
                        )
                        user_answers.append((choice, q["answer"]))
                        st.markdown("---")
                    
                    submit_button = st.form_submit_button(label="Жауаптарды тексеру")
                    
                    if submit_button:
                        score = 0
                        for choice, correct_answer in user_answers:
                            if choice == correct_answer:
                                score += 1
                        
                        # Нәтижелерді шығару
                        st.write(f"### Сенің нәтижең: 5-тен {score}")
                        if score == 5:
                            st.success("Керемет! Сен материалды өте жақсы меңгердің! 🎉")
                            st.balloons()
                        elif score >= 3:
                            st.info("Жақсы нәтиже! Бірақ әлі де дамуға орын бар. 👍")
                        else:
                            st.warning("Кейбір бөлімдерді қайта көріп, қайтадан байқап көру керек! 💪")