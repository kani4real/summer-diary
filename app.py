# st.session_state - бұл сайтты жаңартқанда (F5) қосылған деректер жоғалып кетпеуі үшін керек
if "subjects_data" not in st.session_state:
    st.session_state.subjects_data = copy.deepcopy(DEFAULT_DATA)

# Интерфейстің негізгі бөлігі
tabs_names = list(st.session_state.subjects_data.keys()) + ["➕ Жаңа туынды қосу"]
tabs = st.tabs(tabs_names)

# Барлық пәндер мен туындыларды шығару
for index, (subject, items) in enumerate(st.session_state.subjects_data.items()):
    with tabs[index]:
        st.header(subject)
        
        if len(items) == 0:
            st.info("Бұл пәнге әлі ештеңе қосылмаған. Өзің қосып көр!")
            
        for item_idx, item in enumerate(items):
            st.subheader(item["title"])
            st.write(item["description"])
            st.markdown(f"**[👉 Онлайн көру үшін сілтеме]({item['link']})**")
            
            # Егер туындының квизі болса, оны шығарамыз
            if "quiz" in item and len(item["quiz"]) > 0:
                with st.expander(f"🧠 Квиз тапсыру: {item['title']}"):
                    form_key = f"quiz_form_{subject}_{item_idx}"
                    with st.form(key=form_key):
                        user_answers = []
                        
                        for q_idx, q in enumerate(item["quiz"]):
                            st.write(q["question"])
                            radio_key = f"q_{subject}_{item_idx}_{q_idx}"
                            choice = st.radio(
                                "Жауапты таңдаңыз:", 
                                q["options"], 
                                key=radio_key,
                                index=None
                            )
                            user_answers.append((choice, q["answer"]))
                            st.markdown("---")
                        
                        submit_button = st.form_submit_button(label="Жауаптарды тексеру")
                        
                        if submit_button:
                            score = 0
                            total_questions = len(item["quiz"])
                            for choice, correct_answer in user_answers:
                                if choice == correct_answer:
                                    score += 1
                            
                            st.write(f"### Сенің нәтижең: {total_questions}-тен {score}")
                            if score == total_questions:
                                st.success("Керемет! Сен материалды өте жақсы меңгердің! 🎉")
                                st.balloons()
                            elif score >= total_questions // 2:
                                st.info("Жақсы нәтиже! Бірақ әлі де дамуға орын бар. 👍")
                            else:
                                st.warning("Кейбір бөлімдерді қайта көріп, қайтадан байқап көру керек! 💪")
            st.divider()

# Жаңа туынды қосу формасы
with tabs[-1]:
    st.header("➕ Өз туындыңды немесе пәнді қос")
    st.write("Осы жерден сен базаға жаңа аниме, фильм немесе дорама қоса аласың. Ол бірден тиісті пәннің ішінде пайда болады!")
    
    with st.form("add_new_work_form"):
        # Пәнді таңдау немесе жаңасын жазу
        existing_subjects = list(st.session_state.subjects_data.keys())
        selected_subject = st.selectbox("Пәнді таңдаңыз:", existing_subjects + ["Жаңа пән жасау..."])
        
        new_subject_name = ""
        if selected_subject == "Жаңа пән жасау...":
            new_subject_name = st.text_input("Жаңа пәннің атын жазыңыз (мысалы: 🌍 География):")
            
        new_title = st.text_input("Туындының атауы (мысалы: Наруто):")
        new_desc = st.text_area("Қысқаша сипаттамасы (Не туралы?):")
        new_link = st.text_input("Көруге арналған сілтеме (URL):")
        
        st.markdown("**(Міндетті емес) Квизге арналған 1 сұрақ қосу:**")
        q_text = st.text_input("Сұрақ:")
        q_options = st.text_input("Жауап нұсқалары (үтір арқылы жазыңыз, мысалы: Астана, Алматы, Шымкент):")
        q_answer = st.text_input("Дұрыс жауап (нұсқалардың біреуін дәл көшіріп жазыңыз):")
        
        submit_new = st.form_submit_button("Базаға қосу")
        
        if submit_new:
            if not new_title or not new_desc:
                st.error("Туындының атауы мен сипаттамасын міндетті түрде жазу керек!")
            else:
                target_subject = new_subject_name if selected_subject == "Жаңа пән жасау..." else selected_subject
                
                # Егер жаңа пән болса, оны сөздікке қосамыз
                if target_subject not in st.session_state.subjects_data:
                    st.session_state.subjects_data[target_subject] = []
                
                # Жаңа туынды объектісін жасау
                new_work = {
                    "title": new_title,
                    "description": new_desc,
                    "link": new_link,
                    "quiz": []
                }
                
                # Егер пайдаланушы сұрақ қосса, оны өңдеу
                if q_text and q_options and q_answer:
                    opts_list = [opt.strip() for opt in q_options.split(",")]
                    new_work["quiz"].append({
                        "question": "1. " + q_text,
                        "options": opts_list,
                        "answer": q_answer.strip()
                    })
                    
                st.session_state.subjects_data[target_subject].append(new_work)
                st.success(f"«{new_title}» сәтті қосылды! Жоғарыдағы '{target_subject}' бөліміне өтіп көре аласыз.")
                st.rerun() # Сайтты жаңарту
